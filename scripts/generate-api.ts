// Export the native Rust router's document and its corresponding TypeScript declarations together.
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

async function generate() {
  const check = process.argv.includes("--check");
  const args = [
    "run",
    "--quiet",
    "--locked",
    "-p",
    "betabook-worker",
    "--features",
    "api-spec",
    "--bin",
    "export-openapi",
  ];
  if (!check && process.argv.includes("--partial")) args.push("--", "--partial");
  const document = execFileSync("cargo", args, { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
  const types =
    "// Generated by pnpm api:generate. Edit the Rust API contract.\n" +
    astToString(await openapiTS(JSON.parse(document)));
  for (const [file, content] of [
    ["api/openapi.json", document],
    ["spa/generated/api.d.ts", types],
  ]) {
    if (check) {
      if ((await readFile(file, "utf8")) !== content)
        throw new Error(`${file} is stale. Run pnpm api:generate.`);
    } else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, content);
    }
  }
}
void generate().catch((err: unknown) => {
  console.error(err);
  process.exitCode = 1;
});
